$ErrorActionPreference = "Stop"
cmake -S . -B build -DDSTORE_BUILD_TESTS=OFF -DDSTORE_BUILD_BENCHMARKS=ON
cmake --build build --config Release
New-Item -ItemType Directory -Force docs | Out-Null
function Invoke-Benchmark($name) {
  $exe = Get-ChildItem build -Recurse -File | Where-Object { $_.Name -eq "$name.exe" -or $_.Name -eq $name } | Select-Object -First 1
  if (-not $exe) { throw "Benchmark executable not found: $name" }
  & $exe.FullName
}
$chunk = Invoke-Benchmark "chunk_bench"
$cluster = Invoke-Benchmark "cluster_bench"
$recovery = Invoke-Benchmark "recovery_bench"
